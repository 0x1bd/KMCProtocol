#!/usr/bin/env bash
set -euo pipefail

SERVER_DIR="${KMC_SERVER_DIR:-test_server}"
SERVER_JAR_URL="${KMC_SERVER_JAR_URL:-https://piston-data.mojang.com/v1/objects/4707d00eb834b446575d89a61a11b5d548d8c001/server.jar}"
SERVER_IP="${KMC_SERVER_IP:-127.0.0.1}"
SERVER_PORT="${KMC_SERVER_PORT:-25565}"
JAVA_OPTS="${KMC_SERVER_JAVA_OPTS:--Xmx1024M -Xms1024M}"
PREPARE_ONLY="${KMC_SERVER_PREPARE_ONLY:-false}"
FORCE_DOWNLOAD="${KMC_SERVER_FORCE_DOWNLOAD:-false}"

mkdir -p "$SERVER_DIR"
cd "$SERVER_DIR" || exit

if [[ ! -f server.jar || "$FORCE_DOWNLOAD" == "true" ]]; then
  echo "Downloading Minecraft server jar..."
  if command -v curl >/dev/null 2>&1; then
    curl -L -o server.jar "$SERVER_JAR_URL"
  elif command -v wget >/dev/null 2>&1; then
    wget -O server.jar "$SERVER_JAR_URL"
  else
    echo "Neither curl nor wget is available." >&2
    exit 1
  fi
else
  echo "Using existing Minecraft server jar."
fi

echo "Agreeing to the EULA..."
echo "eula=true" > eula.txt

echo "Configuring server.properties for offline mode..."
cat <<EOL > server.properties
#Minecraft server properties
#Generated by KMCProtocol test_server script
online-mode=false
server-ip=$SERVER_IP
server-port=$SERVER_PORT
level-name=world
gamemode=creative
difficulty=easy
max-players=20
enable-query=false
enable-rcon=false
motd=KMCProtocol test server
EOL

if [[ "$PREPARE_ONLY" == "true" ]]; then
  echo "Prepared server jar: $(pwd)/server.jar"
  exit 0
fi

echo "Starting the Minecraft server on $SERVER_IP:$SERVER_PORT..."
exec java $JAVA_OPTS -jar server.jar nogui
