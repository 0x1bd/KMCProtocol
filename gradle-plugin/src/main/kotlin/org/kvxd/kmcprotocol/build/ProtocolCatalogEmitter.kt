package org.kvxd.kmcprotocol.build

import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.LIST
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.TypeSpec
import java.nio.file.Path

internal class ProtocolCatalogEmitter(
    private val runtimePackage: String,
    private val registryPackage: String,
    private val outputDirectory: Path,
) {
    private val protocolVersion = ClassName("$runtimePackage.core", "ProtocolVersion")
    private val protocolVersionCatalog = ClassName("$runtimePackage.core", "ProtocolVersionCatalog")

    fun emit(specs: List<ProtocolVersionSpec>) {
        val ordered = specs.sortedWith(compareBy({ it.protocolVersion }, { it.minecraftVersion }))
        val catalog = TypeSpec.objectBuilder("Protocols").addSuperinterface(protocolVersionCatalog)

        ordered.forEach { spec ->
            catalog.addProperty(
                PropertySpec.builder(spec.catalogEntryName, protocolVersion)
                    .initializer(
                        CodeBlock.builder()
                            .add("%T(\n⇥", protocolVersion)
                            .add("minecraftVersion = %S,\n", spec.minecraftVersion)
                            .add("protocolVersion = %L,\n", spec.protocolVersion)
                            .add("protocolResourcePath = %S,\n", spec.protocolResourcePath)
                            .add(
                                "registrySource = %T,\n",
                                ClassName("$registryPackage.${spec.packageSuffix}", "GeneratedPacketRegistry"),
                            )
                            .add("⇤)")
                            .build()
                    )
                    .build()
            )
        }

        catalog.addProperty(
            PropertySpec.builder("versions", LIST.parameterizedBy(protocolVersion), KModifier.OVERRIDE)
                .initializer(
                    CodeBlock.builder().apply {
                        if (ordered.isEmpty()) {
                            add("emptyList()")
                            return@apply
                        }
                        add("listOf(\n⇥")
                        ordered.forEachIndexed { index, spec ->
                            if (index > 0) add(",\n")
                            add("%L", spec.catalogEntryName)
                        }
                        add("\n⇤)")
                    }.build()
                )
                .build()
        )

        ordered.lastOrNull()?.let { latest ->
            catalog.addProperty(
                PropertySpec.builder("latest", protocolVersion)
                    .initializer("%L", latest.catalogEntryName)
                    .build()
            )
        }

        FileSpec.builder(registryPackage, "Protocols")
            .addFileComment("Generated by the kmcprotocol Gradle plugin from PrismarineJS minecraft-data.\n")
            .addFileComment("Do not edit.\n")
            .addType(catalog.build())
            .build()
            .writeTo(outputDirectory)
    }
}
